/**
 * 解析 docs/textbook-definitions.md:取「結構」「機構」「機器」開頭的段落(可用 `-`、`**`、`#` 等 Markdown 標記)。
 * 回傳黑板左區內容;內容不足時回傳 null(改用預設)。
 */
export function parseDefinitions(md) {
  if (!md || !md.trim()) return null;
  const lines = md.split(/\r?\n/).map(s => s.replace(/^[\s>#*\-•\d.]+/, '').replace(/\*\*/g, '').trim()).filter(Boolean);
  const pick = k => lines.find(l => l.startsWith(k) && /[::]/.test(l.slice(k.length, k.length + 3)));
  const found = ['結構', '機構', '機器'].map(pick);
  if (found.some(f => !f)) return null;
  return { title: '結構・機構・機器', lines: found.map(text => ({ text: text.replace(/^(..)\s*[::]\s*/, '$1:'), chalk: 'white' })) };
}
